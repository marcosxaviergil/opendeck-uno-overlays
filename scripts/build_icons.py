"""Regenerate uno/glyphs.py, pi/js/glyphs.js, pi/css/symbols.css and images/*.svg from Material Symbols.

Source: google/material-design-icons, variablefont/MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf
and .codepoints (Apache-2.0). Needs fontTools + brotli (build time only, not at runtime):
    python3 scripts/build_icons.py <path to the .ttf> <path to the .codepoints>
"""

import base64
import io
import json
import pathlib
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# Glyph per plugin use. Keys are used by code; values are Material Symbols names.
ICONS = {
    "showall": "visibility",
    "hideall": "visibility_off",
    "toggle": "layers",
    "numericfields": "exposure_plus_1",
    "multiplier": "calculate",
    "knob": "tune",
    "display": "numbers",
    "nextslot": "skip_next",
    "prevslot": "skip_previous",
    "slotwheel": "playlist_play",
    "reveal": "quiz",
    "dialvalue": "edit",
    "visor": "preview",
    "timer": "timer",
    "obsscene": "videocam",
    "obsrefresh": "refresh",
    "plugin": "live_tv",
    "macro": "bolt",
    "panic": "layers_clear",
    "restore": "restore",
    "snapshot": "bookmarks",
    "shift": "shift",
    "clock": "hourglass_top",
    "undo": "undo",
    "lock": "lock",
    "swap": "swap_horiz",
    "cycle": "sync",
    "reset": "restart_alt",
    "datasource": "table_rows",
    "template": "text_fields",
    "vote": "how_to_vote",
    "goal": "flag",
    "status": "network_check",
    "lockdesk": "keyboard_lock",
    "search": "search",
    "star": "star",
    "history": "history",
    "download": "download",
    "add": "add",
    "delete": "delete",
    "upload": "upload",
    "link": "link",
    "up": "arrow_upward",
    "down": "arrow_downward",
    "close": "close",
    "help": "help",
    "language": "language",
}

root = pathlib.Path(__file__).resolve().parent.parent / "plugin" / "dev.br.consciencia.opendeck.uno-overlays.sdPlugin"
ttf, codepoints = sys.argv[1], sys.argv[2]
names = {}
with open(codepoints) as lines:
    for line in lines:
        name, code = line.split()
        names.setdefault(name, int(code, 16))  # first entry is the official mapping

# Filled, default weight/grade, large optical size: legible on 85-95 px keys.
font = instantiateVariableFont(TTFont(ttf), {"FILL": 1, "GRAD": 0, "opsz": 48, "wght": 400})
cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
actions = [a["UUID"].rsplit(".", 1)[-1] for a in json.loads((root / "manifest.json").read_text())["Actions"]]
paths = {}  # key images need only the action glyphs; the inspector uses the font
for key in actions + ["plugin"]:
    name = ICONS[key]
    pen = SVGPathPen(glyphs)
    glyphs[cmap[names[name]]].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # font y-up -> SVG y-down
    paths[key] = pen.getCommands()

(root / "uno/glyphs.py").write_text(
    '"""Generated by scripts/build_icons.py from Material Symbols (Apache-2.0). viewBox 0 -960 960 960."""\n\n'
    "PATHS = " + repr(paths) + "\n"
)

(root / "pi/js/glyphs.js").write_text(
    "/* Generated by scripts/build_icons.py: Material Symbols codepoints (Apache-2.0). */\n"
    "window.GLYPHS = " + json.dumps({key: chr(names[name]) for key, name in ICONS.items()}) + ";\n"
)

options = Options()
options.flavor, options.layout_features = "woff2", []
subsetter = Subsetter(options)
subsetter.populate(unicodes=[names[n] for n in ICONS.values()])
subsetter.subset(font)
buffer = io.BytesIO()
font.recalcTimestamp = False  # reproducible output
font.save(buffer)
(root / "pi/css/symbols.css").write_text(  # embedded: OpenDeck serves .woff2 as application/octet-stream
    '@font-face { font-family: "Material Symbols"; src: url("data:font/woff2;base64,'
    + base64.b64encode(buffer.getvalue()).decode()
    + '") format("woff2"); }\n'
    '.ms { font-family: "Material Symbols"; font-weight: normal; font-style: normal; font-size: 18px;'
    " line-height: 1; vertical-align: -4px; margin-right: 6px; }\n"
)

for key in actions + ["plugin"]:  # manifest images, one per action
    (root / f"images/{key}.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960">'
        f'<rect y="-960" width="960" height="960" fill="#000"/>'
        f'<path transform="translate(144 -144) scale(.7)" fill="#FFF" d="{paths[key]}"/></svg>'
    )
